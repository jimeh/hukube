// Command gen writes the protocol method map and source hash. Run from engine/.
package main

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"go/build"
	"go/format"
	"go/parser"
	"go/scanner"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"slices"
	"strconv"
	"strings"

	"github.com/jimeh/hukube/engine/internal/protocol"
)

func typeName(t reflect.Type) (string, error) {
	if t == reflect.TypeFor[protocol.None]() {
		return "undefined", nil
	}
	if t.PkgPath() == reflect.TypeFor[protocol.None]().PkgPath() && t.Name() != "" && !strings.Contains(t.Name(), "[") {
		return t.Name(), nil
	}
	if t.Kind() == reflect.Slice {
		name, err := typeName(t.Elem())
		if err == nil && name != "undefined" {
			return name + "[]", nil
		}
	}
	return "", fmt.Errorf("unsupported protocol method type: %v", t)
}

func methodMap() ([]byte, error) {
	var body bytes.Buffer
	imports := make(map[string]bool)
	for _, kind := range []protocol.MethodKind{protocol.MethodKindRequest, protocol.MethodKindTopic} {
		name, result := "Requests", "result"
		if kind == protocol.MethodKindTopic {
			name, result = "Topics", "data"
		}
		fmt.Fprintf(&body, "export interface %s {\n", name)
		for _, m := range protocol.Methods() {
			if m.Kind != kind {
				continue
			}
			params, err := typeName(m.Params)
			if err != nil {
				return nil, err
			}
			data, err := typeName(m.Result)
			if err != nil {
				return nil, err
			}
			for _, typ := range []string{params, data} {
				if typ != "undefined" {
					imports[strings.TrimSuffix(typ, "[]")] = true
				}
			}
			fmt.Fprintf(&body, "  %q: { params: %s; %s: %s };\n", m.Name, params, result, data)
		}
		body.WriteString("}\n\n")
	}
	var names []string
	for name := range imports {
		names = append(names, name)
	}
	slices.Sort(names)
	var output bytes.Buffer
	output.WriteString("// Code generated by engine/internal/protocol/gen. DO NOT EDIT.\n\nimport type {\n")
	for _, name := range names {
		fmt.Fprintf(&output, "  %s,\n", name)
	}
	output.WriteString("} from \"./protocol.gen.ts\";\n\n")
	output.Write(body.Bytes())
	output.WriteString("export type RequestMethod = keyof Requests;\nexport type TopicMethod = keyof Topics;\n")
	return output.Bytes(), nil
}

func sourceTokens(name string, source []byte) ([]byte, error) {
	var scan scanner.Scanner
	var scanErr error
	files := token.NewFileSet()
	scan.Init(files.AddFile(name, -1, len(source)), source, func(pos token.Position, msg string) {
		if scanErr == nil {
			scanErr = fmt.Errorf("%s: %s", pos, msg)
		}
	}, 0)
	var output bytes.Buffer
	for {
		_, tok, literal := scan.Scan()
		if tok == token.EOF {
			break
		}
		// Explicit and inserted semicolons are the same Go token.
		if tok == token.SEMICOLON {
			literal = ""
		}
		fmt.Fprintf(&output, "%d:%d:%s;", tok, len(literal), literal)
	}
	return output.Bytes(), scanErr
}

func protocolHash(dir string) (string, error) {
	entries, err := os.ReadDir(dir) // ReadDir sorts by file name.
	if err != nil {
		return "", err
	}
	hash := sha256.New()
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || strings.HasSuffix(name, ".gen.go") {
			continue
		}
		source, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return "", err
		}
		file, err := parser.ParseFile(token.NewFileSet(), name, source, parser.ImportsOnly)
		if err != nil {
			return "", err
		}
		for _, spec := range file.Imports {
			importPath, err := strconv.Unquote(spec.Path.Value)
			if err != nil {
				return "", err
			}
			pkg, err := build.Default.Import(importPath, dir, build.FindOnly)
			if err != nil || !pkg.Goroot {
				return "", fmt.Errorf("protocol imports non-standard package %q", importPath)
			}
		}
		tokens, err := sourceTokens(name, source)
		if err != nil {
			return "", err
		}
		_, _ = hash.Write(tokens)
	}
	return fmt.Sprintf("%x", hash.Sum(nil))[:16], nil
}

func generate() error {
	methods, err := methodMap()
	if err != nil {
		return err
	}
	hash, err := protocolHash("internal/protocol")
	if err != nil {
		return err
	}
	source, err := format.Source(fmt.Appendf(nil, "// Code generated by engine/internal/protocol/gen. DO NOT EDIT.\n\npackage protocol\n\n// Hash identifies the protocol definition. The Engine sends it in Hello; a UI\n// with another value is of another build.\nconst Hash = %q\n", hash))
	if err != nil {
		return err
	}
	if err := os.WriteFile("../packages/engine-client/src/methods.gen.ts", methods, 0o644); err != nil {
		return err
	}
	return os.WriteFile("internal/protocol/hash.gen.go", source, 0o644)
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
